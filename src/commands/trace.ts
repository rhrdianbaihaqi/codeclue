import { resolve } from "node:path";
import { estimateTokens, savedPercent } from "../lib/count";
import { CliError } from "../lib/errors";
import { assertSourceFile, isSupportedSource } from "../lib/files";
import { formatExports, listExports } from "../lib/exports";
import type { ExportEntry } from "../lib/exports";
import { openProject } from "../lib/project";
import { graph } from "./graph";
import type { GraphResult } from "./graph";
import { outlineSourceFile } from "./outline";

/** Dari paling rinci ke paling ringkas. */
export type Layer = "full" | "outline" | "exports" | "path";
const LADDER: readonly Layer[] = ["full", "outline", "exports", "path"];

/** File yang diimpor sebanyak ini (atau lebih) naik satu lapis. */
export const FAN_IN_PROMOTE = 3;
export const DEFAULT_TRACE_DEPTH = 2;

/**
 * Outline yang nyaris tidak menghemat (file hampir murni deklarasi tipe) turun ke
 * lapis `exports` bila file cukup besar. Ambang konservatif: file kecil tetap
 * outline, dan penurunan selalu tercatat di `reasons`.
 */
export const OUTLINE_DEMOTE_MIN_TOKENS = 1500;
export const OUTLINE_DEMOTE_BELOW_SAVED = 30;

/** Apakah outline sebesar `outlineTokens` terlalu boros untuk file `originalTokens`? */
export function shouldDemoteOutline(originalTokens: number, outlineTokens: number): boolean {
  return (
    originalTokens >= OUTLINE_DEMOTE_MIN_TOKENS &&
    savedPercent(originalTokens, outlineTokens) < OUTLINE_DEMOTE_BELOW_SAVED
  );
}

export interface TraceFile {
  path: string;
  depth: number;
  layer: Layer;
  /** Alasan lapis bergeser dari tabel dasar (kosong bila tidak bergeser). */
  reasons: string[];
  fanIn: number;
  /** Token file kalau dibaca utuh. */
  originalTokens: number;
  /** Token isi yang ditampilkan di lapisnya (0 untuk `path`). */
  tokens: number;
  content: string;
  exports?: ExportEntry[];
}

export interface TraceTotals {
  files: number;
  /** Token kalau semua file dalam peta dibaca utuh. */
  fullTokens: number;
  /** Token teks yang sebenarnya dikeluarkan (stdout). */
  traceTokens: number;
  savedPercent: number;
}

export interface TraceResult {
  entry: string;
  depth: number;
  files: TraceFile[];
  external: GraphResult["external"];
  unresolved: GraphResult["unresolved"];
  cycles: GraphResult["cycles"];
  totals: TraceTotals;
}

export interface TraceOptions {
  depth?: number;
  /** Tampilkan entry sebagai outline, bukan isi utuh. */
  outlineEntry?: boolean;
  cwd?: string;
  warn?: (message: string) => void;
}

export interface ClassifyInput {
  depth: number;
  maxDepth: number;
  fanIn: number;
  isEntry: boolean;
  /** Entry dikecualikan dari lapis `full` (hanya berlaku bila `isEntry`). */
  outlineEntry?: boolean;
  isTest: boolean;
  isDeclaration: boolean;
  isGenerated: boolean;
  parsable: boolean;
}

const TEST_FILE = /\.(test|spec)\.[cm]?[jt]sx?$/i;
const DECLARATION_FILE = /\.d\.[cm]?ts$/i;
const GENERATED_PATH = /(^|\/)(__generated__|generated)\/|\.(generated|gen)\.[cm]?[jt]sx?$/i;
const GENERATED_HEADER = /@generated|auto-?generated|do not edit|generated by/i;

export const isTestFile = (path: string): boolean => TEST_FILE.test(path);
export const isDeclarationFile = (path: string): boolean => DECLARATION_FILE.test(path);
export const isGeneratedFile = (path: string, text: string): boolean =>
  GENERATED_PATH.test(path) || GENERATED_HEADER.test(text.slice(0, 1024));

/**
 * Lapis dasar dari kedalaman (SPEC: 0 utuh, 1 outline, 2 export, 3+ path;
 * di luar `--depth` selalu path), lalu bergeser: fan-in tinggi naik satu lapis
 * (tidak sampai `full`), test turun jadi path, `.d.ts`/generated turun satu lapis.
 * Entry tidak pernah bergeser.
 */
export function classify(input: ClassifyInput): { layer: Layer; reasons: string[] } {
  if (input.isEntry) return { layer: input.outlineEntry === true ? "outline" : "full", reasons: [] };

  const reasons: string[] = [];
  let index = input.depth > input.maxDepth ? 3 : Math.min(input.depth, 3);

  if (input.fanIn >= FAN_IN_PROMOTE && index > 1) {
    index -= 1;
    reasons.push(`fan-in ${input.fanIn}, promoted`);
  }
  if (input.isTest) {
    index = 3;
    reasons.push("test file");
  } else {
    if (input.isDeclaration && index < 3) {
      index += 1;
      reasons.push(".d.ts, demoted");
    }
    if (input.isGenerated && index < 3) {
      index += 1;
      reasons.push("generated, demoted");
    }
  }
  if (!input.parsable) {
    index = 3;
    reasons.push("not a TS/JS source");
  }

  return { layer: LADDER[index]!, reasons };
}

export function trace(filePath: string, options: TraceOptions = {}): TraceResult {
  const rawWarn = options.warn ?? ((message: string) => process.stderr.write(`${message}\n`));
  const seen = new Set<string>();
  const warn = (message: string): void => {
    if (seen.has(message)) return;
    seen.add(message);
    rawWarn(message);
  };
  const maxDepth = options.depth ?? DEFAULT_TRACE_DEPTH;
  const cwd = options.cwd ?? process.cwd();

  if (!Number.isInteger(maxDepth) || maxDepth < 0) {
    throw new CliError("EARGS", `--depth must be a non-negative integer, got ${String(maxDepth)}`);
  }
  assertSourceFile(filePath);
  // Satu tingkat lebih dalam dari --depth: node di sana tampil sebagai path saja,
  // supaya pembaca tahu apa yang ada di luar batas.
  const g = graph(filePath, { depth: maxDepth + 1, cwd, warn });

  const project = openProject(filePath, warn);
  const files: TraceFile[] = [];

  for (const node of g.nodes) {
    const abs = resolve(cwd, node.path);
    const isEntry = node.depth === 0;

    let text = "";
    let readable = true;
    try {
      text = readFileSync(abs, "utf8");
    } catch {
      readable = false;
      warn(`Warning: cannot read ${node.path}; listed as path only.`);
    }

    const { layer, reasons } = classify({
      depth: node.depth,
      maxDepth,
      fanIn: node.importedBy.length,
      isEntry,
      outlineEntry: options.outlineEntry === true,
      isTest: isTestFile(node.path),
      isDeclaration: isDeclarationFile(node.path),
      isGenerated: isGeneratedFile(node.path, text),
      parsable: isSupportedSource(abs) && readable,
    });

    const originalTokens = estimateTokens(text);
    const file: TraceFile = {
      path: node.path,
      depth: node.depth,
      layer,
      reasons,
      fanIn: node.importedBy.length,
      originalTokens,
      tokens: 0,
      content: "",
    };

    if (layer === "full") {
      file.content = text.trimEnd();
    } else if (layer === "outline" || layer === "exports") {
      const sf = project.addSourceFileAtPath(abs);
      if (layer === "outline") {
        // Pemangkasan import bisa menyisakan baris kosong di awal.
        file.content = outlineSourceFile(sf, node.path, warn).outline.replace(/^\s*\n/, "").trimEnd();
        const outlineTokens = estimateTokens(file.content);
        if (!isEntry && shouldDemoteOutline(originalTokens, outlineTokens)) {
          const entries = listExports(sf);
          const exportsText = formatExports(entries);
          if (estimateTokens(exportsText) < outlineTokens) {
            file.layer = "exports";
            file.exports = entries;
            file.content = exportsText;
            file.reasons.push(
              `outline saves ${savedPercent(originalTokens, outlineTokens)}% of ~${originalTokens} tokens, ` +
                `exports only; see: clue outline ${node.path}`,
            );
          }
        }
      } else {
        file.exports = listExports(sf);
        file.content = formatExports(file.exports);
      }
      project.removeSourceFile(sf);
    }
    file.tokens = estimateTokens(file.content);
    files.push(file);
  }

  const result: TraceResult = {
    entry: g.entry,
    depth: maxDepth,
    files,
    external: g.external,
    unresolved: g.unresolved,
    cycles: g.cycles,
    totals: { files: files.length, fullTokens: 0, traceTokens: 0, savedPercent: 0 },
  };

  const fullTokens = files.reduce((sum, f) => sum + f.originalTokens, 0);
  const traceTokens = estimateTokens(formatTrace(result));
  result.totals = { files: files.length, fullTokens, traceTokens, savedPercent: savedPercent(fullTokens, traceTokens) };
  return result;
}

/** Teks untuk agent. Sengaja tidak memuat `totals` — angka itu dihitung dari teks ini. */
export function formatTrace(result: TraceResult): string {
  const out: string[] = [`# trace ${result.entry} (depth ${result.depth})`];

  for (const f of result.files) {
    if (f.layer === "path") continue;
    const tags = [f.depth === 0 ? `entry · ${f.layer}` : f.layer, ...f.reasons].join(" · ");
    out.push("", `### ${f.path} [${tags}]`);
    if (f.content !== "") out.push(f.content);
  }

  const pathOnly = result.files.filter((f) => f.layer === "path");
  if (pathOnly.length > 0) {
    out.push("", "### path only");
    for (const f of pathOnly) out.push(f.reasons.length > 0 ? `${f.path}  (${f.reasons.join(", ")})` : f.path);
  }
  if (result.external.length > 0) {
    out.push("", "### external", result.external.map((e) => e.name).join(", "));
  }
  if (result.unresolved.length > 0) {
    out.push("", "### unresolved");
    for (const u of result.unresolved) out.push(`${u.specifier}  <- ${u.from}`);
  }
  if (result.cycles.length > 0) {
    out.push("", "### cycles");
    for (const cycle of result.cycles) out.push(cycle.join(" <-> "));
  }
  return out.join("\n");
}
